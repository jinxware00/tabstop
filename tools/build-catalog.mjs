import { readFile, writeFile, readdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const json = async (file) =>
  JSON.parse(await readFile(path.join(root, file), "utf8"));
const languages = await json("Snippets/languages.json");
const records = [];
const manifest = await json("Snippets/manifest.json");
for (const [language, entries] of Object.entries(manifest))
  for (const entry of entries) {
    records.push({
      language,
      level: entry.level,
      topic: entry.topic,
      title: entry.title,
      code: await readFile(path.join(root, "Snippets", entry.file), "utf8"),
    });
  }
records.push(...(await json("Snippets/legacy.json")));
for (const file of (await readdir(path.join(root, "Snippets/packs"))).sort()) {
  if (file.endsWith(".json"))
    records.push(...(await json(`Snippets/packs/${file}`)));
}
const seen = new Set();
const snippets = [];
for (const record of records) {
  const code = record.code.replace(/\r\n/g, "\n").trim();
  if (!languages.some((language) => language.name === record.language))
    throw new Error(`Unknown language: ${record.language}`);
  if (!["Beginner", "Intermediate", "Advanced"].includes(record.level))
    throw new Error(`Invalid level: ${record.title}`);
  if (!record.title || !record.topic || code.length < 15 || code.length > 2200)
    throw new Error(`Invalid snippet: ${record.title}`);
  const opens = [...code.matchAll(/⟦/g)],
    closes = [...code.matchAll(/⟧/g)];
  if (
    opens.length !== 1 ||
    closes.length !== 1 ||
    opens[0].index >= closes[0].index - 1
  )
    throw new Error(`Exactly one nonempty gap required: ${record.title}`);
  const full = code.replace(/[⟦⟧]/g, "");
  const key = record.language + ":" + full;
  if (seen.has(key)) continue;
  seen.add(key);
  const id = createHash("sha256").update(key).digest("hex").slice(0, 12);
  snippets.push({
    id,
    language: record.language,
    level: record.level,
    topic: record.topic,
    title: record.title,
    code: full,
    gap: [opens[0].index, closes[0].index - 1],
  });
}
for (const language of languages) {
  for (const level of ["Beginner", "Intermediate", "Advanced"])
    if (
      !snippets.some(
        (snippet) =>
          snippet.language === language.name && snippet.level === level,
      )
    )
      throw new Error(`Missing ${level}: ${language.name}`);
}
const output = `// Generated by tools/build-catalog.mjs. Edit Snippets/ source files.\nexport const languages = ${JSON.stringify(languages)};\nexport const snippets = ${JSON.stringify(snippets)};\n`;
const destination = path.join(root, "assets/catalog.js");
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== output)
    throw new Error(
      "Catalogue is out of date. Run node tools/build-catalog.mjs.",
    );
} else await writeFile(destination, output);
console.log(
  `${snippets.length} unique snippets · ${languages.length} languages · all three difficulty levels`,
);
